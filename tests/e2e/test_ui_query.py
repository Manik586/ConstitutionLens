def test_duplicate_submit_is_blocked_question_kept_and_cancel_works(page, mock_api, open_app):
    mock_api.query_responses = ["hold", (200, generated_answer())]
    open_app("briefs")
    ask(page, "When is the deposit refundable?")
    expect(page.locator("#searching")).to_be_visible()
    expect(page.locator("#cancelBtn")).to_be_visible()
    expect(page.locator("#askBtn")).to_be_disabled()
    page.locator("#question").press("Enter")  # second submit while running
    page.locator("#askForm").evaluate("f => f.requestSubmit()")
    assert mock_api.count("POST", "/corpora/briefs/query") == 1
    expect(page.locator("#question")).to_have_value("When is the deposit refundable?")

    page.locator("#cancelBtn").click()
    expect(page.locator("#searching")).to_be_hidden()
    expect(page.locator("#askBtn")).to_be_enabled()
    expect(page.locator("#results")).to_be_hidden()
    expect(page.locator("#question")).to_have_value("When is the deposit refundable?")
    mock_api.held[0].fulfill(status=200, content_type="application/json", body=json.dumps(generated_answer()))
    page.wait_for_timeout(200)
    expect(page.locator("#results")).to_be_hidden()  # a cancelled answer is never shown

    page.locator("#askBtn").click()
    expect(page.locator("#results")).to_be_visible()
    assert mock_api.count("POST", "/corpora/briefs/query") == 2


def test_generated_answer_citations_evidence_and_check_render_accurately(page, mock_api, open_app):
    mock_api.config = default_config(generation=True)
    mock_api.query_responses = [(200, generated_answer())]
    open_app("briefs")
    expect(page.locator("#generateWrap")).to_be_visible()
    page.locator("#generate").check()
    ask(page)
    [q] = mock_api.find("POST", "/corpora/briefs/query")
    assert q["json"]["generate"] is True

    answer = page.locator("#answerPanel")
    expect(page.locator("#answerStatus")).to_contain_text("Partial answer")
    expect(page.locator("#answerKind")).to_contain_text("Generated by the LLM")
    expect(page.locator("#notices")).to_contain_text("1 statement was removed by the evidence-support check.")
    expect(answer.locator(".claim")).to_have_count(2)
    expect(answer.locator(".claim").first).to_have_text("The security deposit is refundable within thirty days of vacating [E1].")
    expect(answer.locator(".cite")).to_have_text(["[E1]", "[E2]"])
    expect(answer.locator(".tag", has_text="inference")).to_have_count(1)

    # Evidence cards: id, filename, page, corpus, excerpt; cited ones marked.
    cards = page.locator("#evidenceList .evidence")
    expect(cards).to_have_count(3)
    expect(page.locator("#evidenceCount")).to_have_text("3 items")
    e3 = page.locator("#evidence-E3")
    expect(e3.locator(".evidence__id")).to_have_text("E3")
    expect(e3.locator(".evidence__title")).to_have_text("addendum.pdf")
    expect(e3.locator(".tag--cited")).to_have_count(0)
    expect(page.locator("#evidence-E1 .tag--cited")).to_have_count(1)

    # Clicking [E2] opens and focuses the matching card.
    answer.locator(".cite", has_text="[E2]").click()
    e2 = page.locator("#evidence-E2")
    expect(e2.locator("details")).to_have_attribute("open", "")
    expect(e2).to_be_focused()
    expect(e2.locator(".evidence__facts")).to_contain_text("lease.pdf")
    expect(e2.locator(".evidence__facts dt").nth(1)).to_have_text("Page")
    expect(e2.locator(".evidence__facts dd").nth(1)).to_have_text("4")
    expect(e2.locator(".evidence__loc")).to_contain_text("page 4")
    expect(e2.locator(".evidence__facts")).to_contain_text("briefs")
    expect(e2.locator(".evidence__excerpt")).to_have_text("Rent is payable on the fifth day of each month.")

    # Phase 6: actual statuses, kept vs removed, never upgraded.
    check = page.locator("#checkPanel")
    expect(page.locator("#checkHeading")).to_have_text("Evidence-support check (does the cited evidence support each claim?)")
    expect(check.locator(".panel__note")).to_have_text("This checks textual support in the retrieved documents only — not whether the law is correct or current.")
    expect(check.locator(".check__summary")).to_have_text("4 claims checked (lexical): 2 supported, 1 insufficient, 1 contradicted.")
    kept = check.locator(".check-list:not(.check-list--removed) .check-item")
    removed = check.locator(".check-list--removed .check-item")
    expect(kept).to_have_count(2)
    expect(removed).to_have_count(2)
    expect(kept.first.locator(".badge")).to_contain_text("Supported")
    insufficient = removed.filter(has_text="Late rent incurs a penalty")
    expect(insufficient.locator(".badge")).to_contain_text("Insufficient support")
    expect(insufficient).to_contain_text("Only 20% of the key terms appear in the cited evidence.")
    contradicted = removed.filter(has_text="The addendum allows pets.")
    expect(contradicted.locator(".badge")).to_contain_text("Contradicted")
    expect(contradicted).to_contain_text("E3 says the addendum concerns parking only.")
    expect(check).to_contain_text("the answer may be shorter than what the model originally wrote")
    for overclaim in ("verified", "legally correct", "good law", "guaranteed", "accurate statement of law"):
        assert overclaim not in check.inner_text().lower()
    # Citation buttons in the check section also lead to evidence.
    contradicted.locator(".cite", has_text="[E3]").click()
    expect(page.locator("#evidence-E3")).to_be_focused()


