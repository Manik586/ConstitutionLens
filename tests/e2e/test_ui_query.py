def test_api_errors_and_network_failure_keep_the_ui_usable(page, mock_api, open_app):
    mock_api.query_responses = [
        (500, {"error": "internal_error", "message": "Internal error; the details are in the server log."}),
        "network",
        (422, {"error": "invalid_request", "message": "question: String should have at most 2000 characters"}),
        (409, {"error": "corpus_not_ready", "message": "Corpus 'briefs' has not been built yet; build it before querying."}),
        (200, extractive_answer()),
    ]
    open_app("briefs")
    ask(page)
    expect(page.locator("#queryError")).to_have_text("Internal error; the details are in the server log.")
    page.locator("#askBtn").click()
    expect(page.locator("#queryError")).to_have_text("Cannot reach the server. Check that it is running and that you are online.")
    page.locator("#askBtn").click()
    expect(page.locator("#queryError")).to_have_text("question: String should have at most 2000 characters")
    gets = mock_api.count("GET", "/corpora/briefs")
    page.locator("#askBtn").click()
    expect(page.locator("#queryError")).to_contain_text("has not been built yet")
    page.wait_for_timeout(200)
    assert mock_api.count("GET", "/corpora/briefs") > gets  # a 409 re-fetches the corpus status
    page.locator("#askBtn").click()
    expect(page.locator("#results")).to_be_visible()
    expect(page.locator("#queryError")).to_be_hidden()


def test_hostile_content_renders_as_inert_text(page, mock_api, open_app):
    evil = '<img src=x onerror="window.__xss=1">'
    mock_api.corpora.append(corpus("evil", evil, "ready", 1, 1))
    answer = extractive_answer()
    answer["claims"][0]["statement"] = f"{evil} [1]"
    answer["evidence"][0]["document_title"] = f"{evil}.pdf"
    answer["evidence"][0]["chunk"]["text"] = f"<script>window.__xss=2</script>{evil}"
    answer["notices"] = [evil]
    mock_api.query_responses = [(200, answer)]
    mock_api.upload_response = (200, {"corpus": corpus("evil", evil, "uploaded", 2, 1), "files": [
        {"filename": f"{evil}.pdf", "status": "rejected", "reason": evil, "pages": None, "size_bytes": 1, "stored_as": None}]})
    open_app("evil")
    expect(page.locator("#corpusTitle")).to_have_text(evil)
    page.locator("#fileInput").set_input_files([{"name": "x.pdf", "mimeType": "application/pdf", "buffer": b"%PDF-1.4"}])
    expect(page.locator(".file-result--rejected")).to_contain_text(evil)
    mock_api.corpora[-1]["status"] = "ready"
    page.locator('.corpus-item[data-corpus-id="briefs"]').click()
    page.locator('.corpus-item[data-corpus-id="evil"]').click()
    ask(page)
    expect(page.locator("#answerPanel .claim").first).to_contain_text(evil)
    page.locator("#evidence-E1 summary").click()
    expect(page.locator("#evidence-E1 .evidence__excerpt")).to_have_text(f"<script>window.__xss=2</script>{evil}")
    expect(page.locator("#notices")).to_have_text(evil)
    assert page.evaluate("() => window.__xss") is None
    assert page.locator("main img, aside img, #results script").count() == 0


def test_keyboard_only_main_flow(page, mock_api, open_app):
    mock_api.query_responses = [(200, extractive_answer())]
    open_app()
    page.locator("body").focus()
    page.keyboard.press("Tab")
    expect(page.locator(".skip-link")).to_be_focused()
    page.keyboard.press("Tab")
    expect(page.locator("#newCorpusBtn")).to_be_focused()
    page.keyboard.press("Tab")
    page.keyboard.press("Tab")
    expect(page.locator('.corpus-item[data-corpus-id="briefs"]')).to_be_focused()
    page.keyboard.press("Enter")
    expect(page.locator("#corpusTitle")).to_have_text("Case briefs")
    # Delete dialog: opens with focus inside, Escape returns focus to the trigger.
    page.locator("#deleteBtn").focus()
    page.keyboard.press("Enter")
    expect(page.locator("#deleteCancel")).to_be_focused()
    page.keyboard.press("Tab")
    expect(page.locator("#deleteConfirm")).to_be_focused()
    page.keyboard.press("Escape")
    expect(page.locator("#deleteBtn")).to_be_focused()
    assert mock_api.count("DELETE", "/corpora/briefs") == 0
    # Upload controls are reachable, then the question box.
    page.keyboard.press("Tab")
    expect(page.locator("#fileInput")).to_be_focused()
    page.locator("#question").focus()
    page.keyboard.type("What does the lease say about rent?")
    page.keyboard.press("Enter")
    expect(page.locator("#results")).to_be_visible()
    page.locator("#answerPanel .cite").first.focus()
    page.keyboard.press("Enter")
    expect(page.locator("#evidence-E1")).to_be_focused()


